def prompt_dialogue_fix(meta, segs):
    """2차 정밀 전사(keep 구간만) → 최종 대사자막 번역. 시간은 원본 영상 기준 초 그대로."""
    body = "\n".join(f"{a:.2f}\t{b:.2f}\t{t}" for a, b, t in segs)
    return (f"너는 일본 영상 자막 번역가다. 아래는 최종 영상에 실제로 들어갈 구간의 "
            f"정밀 일본어 전사다(시작초\\t끝초\\t대사).\n"
            f"[메타]\n{_meta_block(meta)}\n[일본어대사]\n{body}\n"
            f"[할 일] 각 줄을 자연스러운 한국어 구어체 대사자막으로 번역한다. "
            f"★입력의 **모든 줄을 빠짐없이 번역해 출력**한다 — 짧은 맞장구('응','뭐?','어?'), "
            f"반복되는 말이라도 전부 자막으로 남긴다. 화면에서 일본어가 들리는데 자막이 비면 안 된다. "
            f"예외는 **의미 없는 순수 신음·탄성 소리**(아앙/응웅 등)뿐 — 이것만 (신음)으로 축약하거나 제외한다. "
            f"★노골적·성적 대사(성기·행위·삽입·사정 등 직접 묘사)는 그대로 옮기지 말고 **완곡하게 순화**해 번역한다 "
            f"(예: 신체·행위 직접 표현 → 분위기·감정 위주의 은근한 표현). "
            f"화자 성별을 추정해 speaker에 '여' 또는 '남'. 시간은 입력 값 그대로 유지.\n"
            f'[출력 JSON만] {{"dialogue":[{{"start":초,"end":초,"ko":"","speaker":"여|남"}}]}}')


def _safe_keep_rule():
    """keep 선정 단계의 노골 대사 차단 — ⓪ 3중 필터는 '대사 있는 구간'을 보호하므로
    노골적인 '말'을 하며 진행되는 장면은 클린본에 살아남는다. 마지막 방어선은 여기:
    LLM이 그런 구간을 아예 고르지 않게 한다(유튜브 안전이 후킹점수보다 우선)."""
    return ("(0)★유튜브 안전 — 최우선★ 성기·발기·삽입·사정 등 노골적 성적 대사가 있는 구간, "
            "신음이 섞이거나 정사로 진입하는 구간은 후킹점수가 아무리 높아도 절대 keep하지 않는다. "
            "야릇한 '분위기·긴장'은 좋지만 노골적인 '단어·행위 묘사'는 안 된다. ")


def prompt_auto(meta, segs, target_sec=60, hint="", pos="mid", style="3min"):
    body = "\n".join(f"{k}\t{a:.2f}\t{b:.2f}\t{t}" for k, (a, b, t) in enumerate(segs, 1))
    return (f"너는 일본 영상 리뷰어다. 아래 영상의 일본어 자막을 보고 '스토리 핵심만' 골라 "
            f"**약 {target_sec}초 내외 하이라이트 영상**으로 압축하고, 한글 대사자막과 해설 내레이션을 만든다.\n"
            f"{_hint_block(hint)}"
            f"[메타]\n{_meta_block(meta)}\n[일본어자막] 번호\\t시작초\\t끝초\\t대사\n{body}\n"
            f"{_roundup_block(pos, target_sec, style)}{_timeline_rule()}{_style(style)}\n"
            f"[규칙] {_safe_keep_rule()}(1)무음·잡담·반복·비스토리 라인은 버린다. "
            f"(2)스토리(설정·관계·전환·갈등·결말)를 드러내는 핵심 구간만 keep으로 골라 **합쳐서 {target_sec}초 ±20% 목표**. "
            f"(3)도입~결말 흐름이 보이게 고루 분포. 시간은 원본 영상 기준 초.\n"
            f"[출력 JSON만] {{\"summary\":\"3~5줄\",\"stars\":1~5,\"keep\":[[시작,끝],...],"
            f"\"dialogue\":[{{\"start\":초,\"end\":초,\"ko\":\"\",\"speaker\":\"여|남\"}}],\"narration\":[{{\"start\":초,\"end\":초,\"text\":\"\",\"style\":\"기본|강조|정보\"}}]}}")


def prompt_highlight(meta, segs, target_sec=60, hint="", pos="mid", style="3min",
                     with_dialogue=True, nar_rich=False, cutin_tags=None, visual=""):
    """AlphaCut식 하이라이트 추출 — '고루 분포' 대신 '가장 후킹되는 순간'만 골라 몰아 뽑는다."""
    body = "\n".join(f"{k}\t{a:.2f}\t{b:.2f}\t{t}" for k, (a, b, t) in enumerate(segs, 1))
    make = "압축한다" if not with_dialogue else "압축하고, 한글 대사자막과 해설 내레이션을 만든다"
    return (f"너는 일본 영상 리뷰어다. 아래 영상 자막에서 **가장 후킹되는(클릭·시청유지 유발) 순간**만 골라 "
            f"**약 {target_sec}초 내외 하이라이트**로 {make}. 줄거리 요약이 아니라 '반전·긴장·감정 절정'의 밀도 높은 컷.\n"
            f"{_hint_block(hint)}"
            f"[메타]\n{_meta_block(meta)}\n[일본어자막] 번호\\t시작초\\t끝초\\t대사\n{body}\n"
            f"{_visual_block(visual)}"
            f"{_roundup_block(pos, target_sec, style)}{_timeline_rule()}{_style(style)}\n"
            f"{_dialogue_note(with_dialogue)}{_nar_style_rule(nar_rich)}{_cutin_rule(cutin_tags)}"
            f"[하이라이트 규칙] {_safe_keep_rule()}"
            f"(1)잡담·무음·반복은 버린다. "
            f"(2)★고루 분포 금지★ — 앞·중간·뒤 균등이 아니라 **후킹 밀도가 가장 높은 순간에 집중**. "
            f"(3)각 컷마다 hook(후킹점수 1~5, 5=최고)과 reason(왜 후킹인지 한 줄)을 매긴다. "
            f"(4)점수 높은 컷들로 합쳐서 {target_sec}초 ±20% 채운다(부족하면 낮은 점수도 채택, 넘치면 상위만). "
            f"(5)각 컷은 2~15초 권장. 시간은 원본 영상 기준 초.\n"
            f"[출력 JSON만] {{\"summary\":\"3~5줄\",\"stars\":1~5,"
            f"\"picks\":[{{\"start\":초,\"end\":초,\"hook\":1~5,\"reason\":\"\"}}],"
            f"\"keep\":[[시작,끝],...],"  # picks 와 동일 구간(렌더 호환용)
            f"{_dialogue_out(with_dialogue)}"
            f"{_cutin_out(cutin_tags)}"
            f"\"narration\":[{{\"start\":초,\"end\":초,\"text\":\"\","
            f"\"style\":\"{_nar_style_out(nar_rich)}\"}}]}}")


def _nar_style_rule(rich):
    """내레이션 유형(강조·정보) 사용 여부.

    기본은 **끔** — '강조'/'정보'는 색만 바뀔 뿐 실제 연출 효과가 없어서(2026-07-13 사용자
    피드백) 화면만 산만해진다. 필요할 때만 GUI에서 켠다."""
    if rich:
        return ("[내레이션 유형] style 지정 — '기본'(장면 중계)/'강조'(훅·반전·총평)/"
                "'정보'(스펙·레이블·수치). '강조'는 남발하지 말고 총평과 결정적 한 줄에만.\n")
    return ("[★내레이션 유형] style은 **전부 \"기본\"** 으로만 출력한다. "
            "'강조'·'정보' 유형은 쓰지 마라(사용 안 함).\n")


def _nar_style_out(rich):
    return "기본|강조|정보" if rich else "기본"


def _cutin_rule(tags):
    """상황별 짤(움짤) — LLM이 '여기서 어떤 반응 짤이 어울리나'를 골라준다.
    태그는 폴더 이름과 1:1이라 목록 밖은 쓰면 안 된다(없는 태그는 그냥 무시됨)."""
    if not tags:
        return ""
    return ("[상황 짤] 시청자 반응을 대신할 짤을 넣을 자리를 고른다. "
            f"태그는 **반드시 이 목록에서만**: {', '.join(tags)}. "
            "리액션이 필요한 순간(반전·어이없는 대사·민망한 장면)에만 2~4개. "
            "남발하면 촌스럽다. 각 짤은 2~3초.\n")


def _cutin_out(tags):
    if not tags:
        return ""
    return "\"cutins\":[{\"start\":초,\"end\":초,\"tag\":\"" + "|".join(tags) + "\"}],"


def _keep_meta_out():
    """왜 그 구간을 골랐는지 근거를 쓰게 한다 — LLM이 근거를 적으면 선택이 정교해지고,
    나중에 '왜 이 컷?'을 추적할 수 있다(하이라이트 모드엔 이미 picks[].hook/reason이 있음)."""
    return ("\"keep_meta\":[{\"start\":초,\"end\":초,\"beat\":\"도입|관계|전환|갈등|결말\","
            "\"reason\":\"이 구간을 고른 이유 한 줄\"}],")


