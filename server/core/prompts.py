        "· \"들어보셨습니까? 들어봤을 리 없을 겁니다. 제가 방금 만든 말이니까요.\" — 셀프 츳코미\n"
        "· \"쓸데없이 왜 걸레질이냐 하실 수도 있지만, 이 장면이 포인트입니다.\" — 시청자 반응 선수치기\n"
