    if pos == "last":
        b += (" · 이 꼭지가 마지막이므로, 총평 뒤에 마무리 인사 한 줄을 덧붙인다"
              "('오늘도 이상한 영상을 시청해 주셔서 감사합니다. 지금까지 딸감별사였습니다.').\n")
